// Builds app/src/features/sample/sampleBookContent.ts from content/sample-book/
// (the one source of truth: book.json + one Markdown file per chapter).
// Metro only bundles files inside app/, so the content travels as a generated
// module; sample/__tests__/sampleBook.test.ts fails when the two drift apart.
//
// Usage (from app/): node scripts/build-sample-book.js

/* global __dirname */

const fs = require('node:fs');
const path = require('node:path');

const CONTENT_DIR = path.join(__dirname, '..', '..', 'content', 'sample-book');
const OUTPUT_FILE = path.join(__dirname, '..', 'src', 'features', 'sample', 'sampleBookContent.ts');

/** «# Title» on the first line, then the chapter text (paragraphs split by a blank line). */
function parseChapterFile(markdown) {
  const normalized = markdown.replace(/\r\n/g, '\n');
  const match = /^# (.+)\n\n([\s\S]+)$/.exec(normalized);
  if (match === null) throw new Error('chapter file: expected «# Title», a blank line, the text');
  return { title: match[1].trim(), text: match[2].trim() };
}

/** The sample book as the app bundles it. */
function buildSampleBookContent(contentDir = CONTENT_DIR) {
  const book = JSON.parse(fs.readFileSync(path.join(contentDir, 'book.json'), 'utf8'));
  return {
    id: book.id,
    title: book.title,
    author: book.author,
    description: book.description,
    synopsis: book.synopsis,
    genre: book.genre,
    styleProfileId: book.styleProfileId,
    language: book.language,
    chapters: book.chapters.map((chapter) => {
      const { title, text } = parseChapterFile(
        fs.readFileSync(path.join(contentDir, chapter.file), 'utf8'),
      );
      return {
        id: chapter.id,
        title,
        text,
        outline: chapter.outline,
        examples: chapter.examples,
      };
    }),
  };
}

function renderModule(content) {
  return [
    '// GENERATED by app/scripts/build-sample-book.js from content/sample-book/:',
    '// do not edit by hand (edit the content, then run the script).',
    '',
    "import type { SampleBookContent } from './types';",
    '',
    `export const SAMPLE_BOOK_CONTENT: SampleBookContent = ${JSON.stringify(content, null, 2)};`,
    '',
  ].join('\n');
}

async function main() {
  const prettier = require('prettier');
  const source = renderModule(buildSampleBookContent());
  const options = (await prettier.resolveConfig(OUTPUT_FILE)) ?? {};
  const formatted = await prettier.format(source, { ...options, filepath: OUTPUT_FILE });
  fs.writeFileSync(OUTPUT_FILE, formatted);
  console.log(`written ${path.relative(process.cwd(), OUTPUT_FILE)}`);
}

module.exports = { buildSampleBookContent, parseChapterFile };

if (require.main === module) {
  main().catch((error) => {
    console.error(error);
    process.exit(1);
  });
}
