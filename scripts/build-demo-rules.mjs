// Builds firestore.demo.rules (the judges' demo project) from firestore.rules:
// the same per-user rules, where «owner» also needs the judge claim and an
// open demo (config/demo enabled and not expired). Generated, never edited by
// hand: run `node scripts/build-demo-rules.mjs` after changing firestore.rules
// (a test fails while the two are out of step). See docs/judges-demo.md.

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));

const OWNER = `    function isOwner(uid) {
      return request.auth != null && request.auth.uid == uid;
    }`;

const DEMO_OWNER = `    // judges' demo: the owner must also have entered the CURRENT access code
    // (judge claim and server marker, both set by redeemAccessCode) and the
    // demo must be open; a missing document makes get() fail, which denies
    function isOwner(uid) {
      let demo = get(/databases/$(database)/documents/config/demo).data;
      return request.auth != null && request.auth.uid == uid
        && request.auth.token.judge == true
        && demo.enabled == true
        && request.time.toMillis() < demo.expiresAt
        && get(/databases/$(database)/documents/demoAccess/$(uid)).data.codeSha256
          == demo.codeSha256;
    }`;

export function buildDemoRules(rules) {
  if (!rules.includes(OWNER)) {
    throw new Error('firestore.rules: isOwner() changed shape; update scripts/build-demo-rules.mjs');
  }
  return (
    '// GENERATED by scripts/build-demo-rules.mjs from firestore.rules: do not edit.\n' +
    rules.replace(OWNER, DEMO_OWNER)
  );
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const expected = buildDemoRules(readFileSync(`${root}firestore.rules`, 'utf8'));
  if (process.argv.includes('--check')) {
    // used by rules-tests: the committed file must be what this script builds
    const actual = readFileSync(`${root}firestore.demo.rules`, 'utf8');
    if (actual !== expected) {
      console.error('firestore.demo.rules is out of date: run node scripts/build-demo-rules.mjs');
      process.exit(1);
    }
  } else {
    writeFileSync(`${root}firestore.demo.rules`, expected);
    console.log('firestore.demo.rules written');
  }
}
